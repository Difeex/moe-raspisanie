/* Service worker приложения «Моё расписание».

   Задача одна: приложение должно открываться без сети. Оно и так работает
   офлайн — внутри index.html нет ни одного внешнего запроса, — но саму
   страницу браузер по-прежнему просит у сервера, и без интернета показывает
   ошибку. Здесь она берётся из кэша.

   Стратегия — «отдать из кэша, обновить в фоне». Открытие всегда мгновенное и
   не зависит от связи, а свежая версия, если она есть, скачивается следом и
   достаётся при следующем запуске. Обратный порядок (сначала сеть) означал бы
   ожидание на каждом запуске и пустой экран в метро.

   Кэшируется только своё: index.html, манифест, иконки и users.json. Запросы
   к GitHub API (резервные копии) через service worker не проходят вовсе — им
   место в сети, а не в кэше.

   Исключение одно — users.json, список записей входа. Для него порядок
   обратный, сначала сеть: по общей стратегии добавленный пользователь не смог
   бы войти до следующего запуска, потому что первый запрос отдал бы старую
   копию файла. Кэш здесь остаётся запасным вариантом и нужен ровно затем,
   чтобы вход работал без сети.

   Фоновый запрос идёт мимо браузерного кэша (cache: 'no-cache'). Pages отдаёт
   страницу с max-age=600, и без этого браузер десять минут отвечал бы из
   своего кэша, не спрашивая сервер, — свежая сборка задерживалась бы ещё на
   один запуск сверх обычного. Трафика это почти не добавляет: запрос идёт
   условным, и если файл не менялся, сервер отвечает «не менялось» без тела.

   Обнаружив, что страница изменилась, service worker сообщает об этом
   приложению. Само оно перезагружаться не станет — человек может в этот
   момент писать заметку, — но покажет окно с просьбой перезапустить. */

var CACHE = 'raspisanie-v2';
var AUTH = 'users.json';
var ASSETS = ['./', './index.html', './manifest.webmanifest', './' + AUTH,
              './icons/icon-32.png', './icons/icon-192.png', './icons/icon-512.png'];

self.addEventListener('install', function(e){
  // skipWaiting: новая версия вступает в силу сразу, без ожидания закрытия
  // всех вкладок. Приложение одностраничное, «половины старой версии» тут
  // случиться не может.
  e.waitUntil(caches.open(CACHE).then(function(c){ return c.addAll(ASSETS); })
    .then(function(){ return self.skipWaiting(); }));
});

self.addEventListener('activate', function(e){
  e.waitUntil(caches.keys().then(function(keys){
    return Promise.all(keys.filter(function(k){ return k !== CACHE; })
      .map(function(k){ return caches.delete(k); }));
  }).then(function(){ return self.clients.claim(); }));
});

self.addEventListener('fetch', function(e){
  var req = e.request;
  // Чужие адреса не трогаем: это будущая синхронизация с GitHub, ей кэш
  // только помешает. И POST/PUT кэшировать нельзя в принципе.
  if(req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;

  e.respondWith(caches.open(CACHE).then(function(cache){
    if(new URL(req.url).pathname.split('/').pop() === AUTH){
      return fetch(req, { cache: 'no-cache' }).then(function(res){
        if(res && res.status === 200 && res.type === 'basic') cache.put(req, res.clone());
        return res;
      }).catch(function(){
        // Без сети остаётся сохранённая копия. Если её нет — вход не
        // настроен, и приложение откроется локальным календарём.
        return cache.match(req).then(function(cached){
          return cached || new Response('', { status: 504 });
        });
      });
    }

    return cache.match(req).then(function(cached){
      var network = fetch(req, { cache: 'no-cache' }).then(function(res){
        // В кэш кладём только удачные ответы. Иначе туда однажды попадёт
        // страница ошибки и приложение перестанет открываться совсем.
        if(res && res.status === 200 && res.type === 'basic'){
          /* Клоны снимаются сразу, до всякого чтения: тело ответа читается один
             раз, а нужно оно дважды — в кэш и ради номера версии. */
          var дела = [cache.put(req, res.clone())];
          if(изменилась(req, cached, res)) дела.push(сообщитьОСборке(res.clone()));
          return Promise.all(дела).then(function(){ return res; });
        }
        return res;
      }).catch(function(){ return cached; });

      /* Держим воркер живым, пока идёт фоновая закачка.

         Без этого он засыпает сразу, как отдал страницу из кэша, — а качать
         остаётся полтора мегабайта. На настольном браузере они успевают, на
         планшете нет: приложение уходит в фон раньше. Ровно это и случилось у
         живого пользователя — четыре публикации подряд до него не доехали, в
         журнале оставалась сборка четырёхчасовой давности.

         Вызов обёрнут: событие бывает уже закрыто, и тогда браузер бросается
         ошибкой — ронять из-за этого обработчик незачем. */
      try{ e.waitUntil(network); }catch(err){}
      return cached || network;
    });
  }));
});

/* Изменилась ли сама страница приложения.

   Сравниваются метки версии файла, которые отдаёт сервер: etag, а если его
   нет — дата последнего изменения. Содержимое сличать незачем, оно в полтора
   мегабайта, да и читать тело ответа здесь нельзя: оно уйдёт в кэш и
   человеку.

   Если в кэше ещё пусто, это первая установка, а не обновление: сообщать
   человеку не о чем. */
function изменилась(req, cached, res){
  if(!cached) return false;
  var путь = new URL(req.url).pathname.split('/').pop();
  // Следим только за самой страницей: манифест и иконки человека не касаются.
  if(путь && путь !== 'index.html') return false;
  var было = cached.headers.get('etag') || cached.headers.get('last-modified');
  var стало = res.headers.get('etag') || res.headers.get('last-modified');
  return !!(было && стало && было !== стало);
}

/* Номер сборки из скачанного файла.

   Нужен окну обновления: человеку показывают, какая версия пришла, а не та, на
   которой он сидит. Строка в файле выглядит так: var APP_VERSION = '1.3'; —
   ищем её как есть.

   Не нашли — не беда: сообщение уйдёт без номера, и окно покажет заголовок без
   скобок. Формат мог измениться, файл мог прийти битым, и ронять из-за этого
   оповещение о новой версии незачем. */
function версияИзФайла(текст){
  // Кавычки принимаются любые: строка в файле сейчас в одинарных, но менять её
  // вид — не повод остаться без номера.
  var m = /APP_VERSION\s*=\s*['"]([^'"]{1,20})['"]/.exec(текст || '');
  return m ? m[1] : null;
}

/* Сказать открытым окнам приложения, что скачана новая сборка.

   Дальше решает приложение: оно покажет человеку окно с просьбой перезапустить
   и запишет это в журнал. Перезагружать страницу отсюда нельзя — в ней может
   быть недописанная заметка.

   Читается тело целиком — полтора мегабайта. Дорого, но случается это только
   при смене версии, то есть считанные разы за неделю, и чтение включено в ту
   же цепочку, которую держит waitUntil: воркер не уснёт на середине. */
function сообщитьОСборке(копия){
  return копия.text().then(function(текст){
    return послатьОкнам(версияИзФайла(текст));
  }, function(){
    return послатьОкнам(null);
  });
}

function послатьОкнам(версия){
  return self.clients.matchAll({ includeUncontrolled: true }).then(function(окна){
    окна.forEach(function(окно){
      var весть = { type: 'build-updated' };
      if(версия) весть.version = версия;
      окно.postMessage(весть);
    });
  }).catch(function(){});
}
